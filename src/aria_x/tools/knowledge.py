"""Blackboard, asset-graph and memory tools.

This is where an exploration becomes durable knowledge:

* **facts / findings / intents** are :class:`~aria_x.models.Node` rows on one
  Cairn-style blackboard; edges record lineage (``yields``, ``proves``, ...);
* **assets** are ARTEX's shared truth store; nodes anchor to them so the report
  can pivot from an observation to every affected host/endpoint;
* **memory** is a zero-dependency TF-IDF index kept in the key/value table plus
  note nodes, so retrieval survives process restarts and never needs a model
  call (``engine.memory`` is intentionally not imported here).

Every mutation validates its vocabulary (severity, kind, status, asset kind) and
uses identifiers generated by the store — this module never invents an ID.
"""

