SPECIALISTS = ("researcher", "coder", "adviser", "memorist")
MEMORY_SCOPE = "memory"
_MAX_BODY = 20000
_TOKEN = re.compile(r"[A-Za-z0-9_]+|[\u4e00-\u9fff]")


# ---------------------------------------------------------------------------
# validation / coercion helpers
# ---------------------------------------------------------------------------


def _enum(value: Any, allowed: Sequence[str], field: str) -> str:
    text = str(value or "").strip().lower()
    if text not in allowed:
        raise ToolError(f"invalid {field} '{value}'; expected one of {', '.join(allowed)}", tool="knowledge")
    return text


def _as_text(value: Any, limit: int = _MAX_BODY) -> str:
    return truncate(str(value or ""), limit)


def _asset_list(value: Any) -> list[Any]:
    if value is None:
        return []
    if isinstance(value, str):
        return [v.strip() for v in value.split(",") if v.strip()]
    if isinstance(value, (list, tuple, set)):
        return list(value)
    return [value]


def infer_asset_kind(value: str) -> str:
    """Heuristic kind for a bare value; explicit kinds always win."""
    text = (value or "").strip()
    if not text:
        return "artifact"
    if text.startswith(("http://", "https://")):
        return "endpoint"
    try:
        ipaddress.ip_address(text)
        return "ip"
    except ValueError:
        pass
    if re.fullmatch(r"[A-Za-z0-9_.\-]+:\d{1,5}", text):
        return "service"
    host = text.split("/")[0].split("?")[0].strip().lower()
    if re.fullmatch(r"(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}", host):
        return "subdomain" if host.count(".") >= 2 else "root_domain"
    return "artifact"


def _find_asset_by_value(ctx: ToolContext, value: str) -> Asset | None:
    wanted = (value or "").strip().lower()
    if not wanted:
        return None
    for asset in ctx.store.list_assets(ctx.project.id, limit=4000):
        if asset.value.lower() == wanted:
            return asset
    return None


def _upsert_asset(ctx: ToolContext, kind: str | None, value: str, *,
                  parent_value: str | None = None, meta: Mapping[str, Any] | None = None) -> Asset:
    value = str(value or "").strip()
    if not value:
        raise ToolError("asset value must not be empty", tool="knowledge")
    if kind:
        kind = _enum(kind, ASSET_KINDS, "asset kind")
    else:
        kind = infer_asset_kind(value)
    parent_id: str | None = None
    if parent_value:
        parent = _find_asset_by_value(ctx, str(parent_value))
        if parent is None:
            parent = ctx.store.upsert_asset(ctx.project.id, infer_asset_kind(str(parent_value)),
                                            str(parent_value).strip())
        parent_id = parent.id
    asset = ctx.store.upsert_asset(ctx.project.id, kind, value, parent_id=parent_id,
                                   meta=dict(meta or {}))
    emit(ctx, ASSET_FOUND, {"asset_id": asset.id, "kind": asset.kind, "value": asset.value,
                            "parent_id": asset.parent_id})
    return asset


def _attach_assets(ctx: ToolContext, node_id: str, values: Iterable[Any]) -> list[dict[str, str]]:
    anchored: list[dict[str, str]] = []
    for raw in _asset_list(values):
        if not raw:
            continue
        if isinstance(raw, Mapping):
            value = str(raw.get("value") or "").strip()
            kind = raw.get("kind")
            parent_value = raw.get("parent")
        else:
            value, kind, parent_value = str(raw).strip(), None, None
        if not value:
            continue
        try:
            asset = _upsert_asset(ctx, str(kind) if kind else None, value,
                                  parent_value=str(parent_value) if parent_value else None)
        except ToolError:
            continue
        ctx.store.anchor(node_id, asset.id)
        anchored.append({"asset_id": asset.id, "kind": asset.kind, "value": asset.value})
    return anchored


def _intent_edge(ctx: ToolContext, node: Node, intent_id: Any, rel: str = "yields") -> dict[str, str] | None:
    text = str(intent_id or "").strip()
    if not text:
        return None
    parent = ctx.store.find_node(text)
    if parent is None or parent.project_id != ctx.project.id:
        return {"warning": f"intent '{text}' not found; edge skipped"}
    edge = ctx.store.add_edge(ctx.project.id, parent.id, node.id, rel)
    return {"edge_id": edge.id, "src": parent.id, "dst": node.id, "rel": rel}


def _node_brief(node: Node) -> dict[str, Any]:
    meta = node.meta or {}
    out: dict[str, Any] = {"id": node.id, "kind": node.kind, "title": node.title,
                          "status": node.status, "created_at": node.created_at}
    for key in ("severity", "confidence", "cvss", "tags"):
        if key in meta:
            out[key] = meta[key]
    return out


def _asset_brief(asset: Asset) -> dict[str, Any]:
    return {"id": asset.id, "kind": asset.kind, "value": asset.value,
            "parent_id": asset.parent_id, "last_seen": asset.last_seen}


