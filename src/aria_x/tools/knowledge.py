def todo_update(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    todo_id = str(kwargs.get("todo_id") or "").strip()
    title = str(kwargs.get("title") or "").strip()
    status = kwargs.get("status")
    detail = kwargs.get("detail")
    if status not in (None, ""):
        try:
            status = _enum(status, TODO_STATUSES, "todo status")
        except ToolError as exc:
            return ToolResult.failure(exc.message, data={"allowed": list(TODO_STATUSES)})
    if todo_id:
        todo = ctx.store.get_todo(todo_id)  # NotFound propagates to the registry
        if todo.project_id != ctx.project.id:
            return ToolResult.failure(f"todo not found: {todo_id}")
        changes: dict[str, Any] = {}
        if title:
            changes["title"] = truncate(title, 300)
        if status:
            changes["status"] = status
        if detail is not None:
            changes["detail"] = truncate(str(detail), 4000)
        if not changes:
            return ToolResult.failure("nothing to update: provide title, status or detail")
        todo = ctx.store.update_todo(todo.id, **changes)
        action = "updated"
    elif title:
        todos = ctx.store.list_todos(ctx.project.id)
        todo = ctx.store.add_todo(Todo.new(
            ctx.project.id, len(todos) + 1, title, detail=str(detail or ""),
            status=status or "pending",
            intent_id=str(kwargs.get("intent_id") or "") or None))
        action = "created"
    else:
        return ToolResult.failure("provide todo_id to update or title to create a todo")
    emit(ctx, TODO_UPDATED, {"todo_id": todo.id, "title": todo.title, "status": todo.status})
    audit(ctx, "todo_update", action, todo.id, {"status": todo.status})
    data = {"todo_id": todo.id, "title": todo.title, "status": todo.status,
            "detail": truncate(todo.detail, 500), "position": todo.position}
    return ToolResult.success(data, text=json_dumps(data))


def prove_goal(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    summary = _as_text(kwargs.get("summary"), 4000).strip()
    if not summary:
        return ToolResult.failure("summary is required")
    raw_ids = kwargs.get("evidence_ids")
    ids = raw_ids if isinstance(raw_ids, (list, tuple)) else ([raw_ids] if raw_ids else [])
    evidence_ids: list[str] = []
    for raw in ids:
        node = ctx.store.find_node(str(raw))
        if node is None or node.project_id != ctx.project.id:
            return ToolResult.failure(f"unknown evidence id: {raw}",
                                      data={"provided": [str(i) for i in ids]})
        evidence_ids.append(node.id)
    goal = None
    try:
        goals = ctx.store.list_nodes(ctx.project.id, kind="goal", limit=10)
        goal = goals[0] if goals else None
    except Exception:
        goal = None
    if goal is None:
        goal = Node.new(ctx.project.id, "goal", ctx.project.name or "Engagement goal",
                        ctx.project.goal, status="proven", meta={"proven_at": now_iso()})
        ctx.store.add_node(goal)
    goal = ctx.store.update_node(goal.id, status="proven",
                                 body=(goal.body + "\n\n" if goal.body else "") + summary,
                                 meta={**(goal.meta or {}), "proven_at": now_iso(),
                                       "evidence_ids": evidence_ids})
    ctx.store.set_kv(f"project:{ctx.project.id}", "goal_proven",
                     {"goal_id": goal.id, "summary": summary, "evidence_ids": evidence_ids,
                      "at": now_iso()})
    for node_id in evidence_ids:
        ctx.store.add_edge(ctx.project.id, node_id, goal.id, "proves")
    emit(ctx, NODE_CREATED, {"node_id": goal.id, "kind": "goal", "status": "proven",
                             "evidence": len(evidence_ids)})
    audit(ctx, "prove_goal", "proven", goal.id, {"evidence": evidence_ids})
    data = {"goal_id": goal.id, "proven": True, "evidence_ids": evidence_ids,
            "summary": summary}
    return ToolResult.success(data, text=json_dumps(data))


def delegate_specialist(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    specialist = str(kwargs.get("specialist") or "").strip().lower()
    question = str(kwargs.get("question") or "").strip()
    context = str(kwargs.get("context") or "").strip()
    if specialist not in SPECIALISTS:
        return ToolResult.failure(f"unknown specialist '{specialist}'",
                                  data={"allowed": list(SPECIALISTS)})
    if not question:
        return ToolResult.failure("question is required")
    if ctx.delegate is None:
        return ToolResult.failure("specialist delegation is not available in this run")
    prompt = question + (f"\n\nContext:\n{truncate(context, 6000)}" if context else "")
    try:
        answer = ctx.delegate(specialist, prompt)
    except Exception as exc:
        audit(ctx, "delegate_specialist", "error", specialist, {"error": str(exc)})
        return ToolResult.failure(f"delegation failed: {type(exc).__name__}: {exc}")
    if not isinstance(answer, str):
        answer = json_dumps(answer)
    answer = truncate(answer, 12000)
    audit(ctx, "delegate_specialist", "completed", specialist, {"chars": len(answer)})
    data = {"specialist": specialist, "answer": answer, "chars": len(answer)}
    return ToolResult.success(data, text=answer)


def scope_check(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    target = str(kwargs.get("target") or "").strip()
    if not target:
        return ToolResult.failure("target is required")
    if "://" in target:
        decision = ctx.scope.authorize_url(target)
    else:
        host, _, maybe_port = target.partition(":")
        port = int(maybe_port) if maybe_port.isdigit() else None
        decision = ctx.scope.authorize_host(host, port)
    audit(ctx, "scope_check", "allowed" if decision.allowed else "denied", target,
          {"reason": decision.reason})
    data = {"target": target, "decision": decision.to_dict(), "scope": ctx.scope.summary()}
    return ToolResult.success(data, text=json_dumps(data))


