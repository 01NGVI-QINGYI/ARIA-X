def _memory_key(ctx: ToolContext, suffix: str) -> str:
    return f"{ctx.project.id}:{suffix}"


def _tokens(text: str) -> list[str]:
    return [token.lower() for token in _TOKEN.findall(text or "")]


def _index_entries(ctx: ToolContext) -> list[dict[str, Any]]:
    keys = ctx.store.get_kv(MEMORY_SCOPE, _memory_key(ctx, "index"), []) or []
    entries: list[dict[str, Any]] = []
    for key in keys:
        entry = ctx.store.get_kv(MEMORY_SCOPE, key)
        if isinstance(entry, dict) and entry.get("text"):
            entries.append(entry)
    return entries


def memory_store(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    text = _as_text(kwargs.get("text"), 8000).strip()
    if not text:
        return ToolResult.failure("text is required")
    tags = [str(t).strip() for t in _asset_list(kwargs.get("tags")) if str(t).strip()][:20]
    key = f"{ctx.project.id}:{new_id('mem', 10)}"
    entry = {"key": key, "text": text, "tags": tags, "created_at": now_iso(),
             "task_id": ctx.task_id, "agent": ctx.agent}
    ctx.store.set_kv(MEMORY_SCOPE, key, entry)
    index = ctx.store.get_kv(MEMORY_SCOPE, _memory_key(ctx, "index"), []) or []
    index = list(index) + [key]
    ctx.store.set_kv(MEMORY_SCOPE, _memory_key(ctx, "index"), index[-2000:])
    node = Node.new(ctx.project.id, "note", truncate(text, 120), text, status="done",
                    meta={"memory_key": key, "tags": tags, "confidence": "medium"})
    ctx.store.add_node(node)
    emit(ctx, NODE_CREATED, {"node_id": node.id, "kind": "note", "title": truncate(text, 120)})
    audit(ctx, "memory_store", "created", key, {"tags": tags, "chars": len(text)})
    data = {"key": key, "node_id": node.id, "tags": tags, "chars": len(text)}
    return ToolResult.success(data, text=json_dumps(data))


def memory_search(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    query = str(kwargs.get("query") or "").strip()
    if not query:
        return ToolResult.failure("query is required")
    limit = clamp_int(kwargs.get("limit"), 1, 20, 5)
    entries = _index_entries(ctx)
    if not entries:
        data = {"query": query, "count": 0, "items": []}
        return ToolResult.success(data, text=json_dumps(data))
    docs = [_tokens(entry.get("text", "") + " " + " ".join(entry.get("tags") or [])) for entry in entries]
    query_tokens = _tokens(query)
    total = len(docs)
    df: dict[str, int] = {}
    for doc in docs:
        for token in set(doc):
            df[token] = df.get(token, 0) + 1
    idf = {token: math.log((total + 1) / (count + 1)) + 1.0 for token, count in df.items()}

    def weigh(tokens: Sequence[str], unknown_idf: float) -> dict[str, float]:
        tf: dict[str, float] = {}
        for token in tokens:
            tf[token] = tf.get(token, 0.0) + 1.0
        vector = {token: count * idf.get(token, unknown_idf) for token, count in tf.items()}
        norm = math.sqrt(sum(value * value for value in vector.values())) or 1.0
        return {token: value / norm for token, value in vector.items()}

    query_vector = weigh(query_tokens, math.log(total + 1) + 1.0)
    scored: list[tuple[float, dict[str, Any]]] = []
    for entry, doc in zip(entries, docs):
        doc_vector = weigh(doc, math.log(total + 1) + 1.0)
        score = sum(weight * doc_vector.get(token, 0.0) for token, weight in query_vector.items())
        if score > 0:
            scored.append((score, entry))
    scored.sort(key=lambda pair: pair[0], reverse=True)
    items = [{"key": entry.get("key"), "text": truncate(entry.get("text", ""), 500),
              "tags": entry.get("tags") or [], "score": round(score, 4),
              "created_at": entry.get("created_at", "")} for score, entry in scored[:limit]]
    data = {"query": query, "count": len(items), "items": items}
    return ToolResult.success(data, text=json_dumps(data))


