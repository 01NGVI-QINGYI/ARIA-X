  function t(key, vars, lang) {
    const locale = normalizeLanguage(lang);
    const dict = MESSAGES[locale] || MESSAGES[DEFAULT_LANGUAGE];
    const template = Object.prototype.hasOwnProperty.call(dict, key)
      ? dict[key]
      : (Object.prototype.hasOwnProperty.call(MESSAGES[DEFAULT_LANGUAGE], key)
        ? MESSAGES[DEFAULT_LANGUAGE][key]
        : String(key || ""));
    if (!vars || typeof vars !== "object") return String(template);
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => (
      Object.prototype.hasOwnProperty.call(vars, name) &&
      vars[name] !== undefined &&
      vars[name] !== null
        ? String(vars[name])
        : match
    ));
  }

