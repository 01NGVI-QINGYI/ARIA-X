def add_fact(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    title = _as_text(kwargs.get("title"), 300)
    body = _as_text(kwargs.get("body"))
    if not title:
        return ToolResult.failure("title is required")
    confidence = str(kwargs.get("confidence") or "medium").lower()
    if confidence not in {"low", "medium", "high"}:
        return ToolResult.failure("confidence must be low, medium or high")
    meta = {"confidence": confidence, "agent": ctx.agent, "task_id": ctx.task_id,
            "source": "observation", "created_at": now_iso()}
    node = Node.new(ctx.project.id, "fact", title, body, status="done", meta=meta)
    ctx.store.add_node(node)
    edges = []
    edge = _intent_edge(ctx, node, kwargs.get("intent_id"), "yields")
    if edge:
        edges.append(edge)
    assets = _attach_assets(ctx, node.id, kwargs.get("asset_values") or [])
    emit(ctx, NODE_CREATED, {"node_id": node.id, "kind": "fact", "title": title,
                             "confidence": confidence})
    audit(ctx, "add_fact", "created", node.id, {"title": title, "assets": len(assets)})
    data = {"node_id": node.id, "kind": "fact", "title": title, "confidence": confidence,
            "assets": assets, "edges": edges}
    return ToolResult.success(data, text=json_dumps(data))


def add_finding(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    title = _as_text(kwargs.get("title"), 300)
    body = _as_text(kwargs.get("body"))
    if not title:
        return ToolResult.failure("title is required")
    try:
        severity = _enum(kwargs.get("severity"), SEVERITIES, "severity")
    except ToolError as exc:
        return ToolResult.failure(exc.message, data={"allowed": list(SEVERITIES)})
    confidence = str(kwargs.get("confidence") or "medium").lower()
    if confidence not in {"low", "medium", "high"}:
        return ToolResult.failure("confidence must be low, medium or high")
    cvss: float | None = None
    if kwargs.get("cvss") not in (None, ""):
        try:
            cvss = float(kwargs.get("cvss"))
        except (TypeError, ValueError):
            return ToolResult.failure("cvss must be a number between 0 and 10")
        if not 0.0 <= cvss <= 10.0:
            return ToolResult.failure("cvss must be between 0 and 10")

    asset_ids: list[str] = []
    asset_briefs: list[dict[str, str]] = []
    for raw in _asset_list(kwargs.get("asset_values")):
        try:
            asset = _upsert_asset(ctx, raw.get("kind") if isinstance(raw, Mapping) else None,
                                  raw.get("value") if isinstance(raw, Mapping) else raw,
                                  parent_value=(raw.get("parent") if isinstance(raw, Mapping) else None))
        except ToolError:
            continue
        asset_ids.append(asset.id)
        asset_briefs.append({"asset_id": asset.id, "kind": asset.kind, "value": asset.value})

    intent_id = str(kwargs.get("intent_id") or "").strip() or None
    warning = ""
    if intent_id and ctx.store.find_node(intent_id) is None:
        warning = f"intent '{intent_id}' not found; finding stored without a proving edge"
        intent_id = None

    meta: dict[str, Any] = {"agent": ctx.agent, "task_id": ctx.task_id, "source": "observation"}
    if isinstance(kwargs.get("meta"), Mapping):
        meta.update(dict(kwargs["meta"]))
    if warning:
        meta["warning"] = warning
    try:
        node = ctx.store.add_finding(ctx.project.id, title, body, severity=severity,
                                     cvss=cvss, confidence=confidence, asset_ids=asset_ids,
                                     intent_id=intent_id, meta=meta)
    except ToolError:
        raise
    evidence_ids = _store_evidence(ctx, node.id, kwargs.get("evidence"))
    emit(ctx, FINDING_CREATED, {"finding_id": node.id, "title": title, "severity": severity,
                                "cvss": cvss, "assets": len(asset_ids),
                                "evidence": len(evidence_ids)})
    audit(ctx, "add_finding", "created", node.id,
          {"title": title, "severity": severity, "evidence": len(evidence_ids)})
    data = {"finding_id": node.id, "title": title, "severity": severity, "cvss": cvss,
            "confidence": confidence, "assets": asset_briefs, "evidence_ids": evidence_ids,
            "linked_to_intent": bool(intent_id)}
    if warning:
        data["warning"] = warning
    return ToolResult.success(data, text=json_dumps(data))


def _store_evidence(ctx: ToolContext, finding_id: str, raw_evidence: Any) -> list[str]:
    """Persist evidence rows from structured dicts or plain path/URL strings."""
    items = raw_evidence if isinstance(raw_evidence, (list, tuple)) else ([raw_evidence] if raw_evidence else [])
    ids: list[str] = []
    for raw in items:
        if isinstance(raw, Mapping):
            kind = str(raw.get("kind") or "observation")
            path = str(raw.get("path") or raw.get("url") or "")
            excerpt = truncate(redact(str(raw.get("excerpt") or "")), 4000)
            digest = str(raw.get("sha256") or "")
            meta = dict(raw.get("meta") or {})
        elif isinstance(raw, str):
            text = raw.strip()
            if not text:
                continue
            kind = "url" if text.startswith(("http://", "https://")) else "path"
            path, excerpt, digest, meta = text, "", "", {}
        else:
            continue
        if path and not digest:
            candidate = None
            try:
                from .terminal import resolve_in_workdir
                candidate = resolve_in_workdir(ctx, path, must_exist=True)
            except (ToolError, OSError):
                candidate = None
            if candidate is not None and candidate.is_file():
                try:
                    from ..util import sha256_bytes
                    digest = sha256_bytes(candidate.read_bytes())
                    if not excerpt:
                        excerpt = truncate(redact(candidate.read_text("utf-8", "replace")), 2000)
                except OSError:
                    pass
        evidence = Evidence(id=new_id("ev"), project_id=ctx.project.id, finding_id=finding_id,
                            kind=kind, path=path, sha256=digest, excerpt=excerpt,
                            meta=meta, created_at=now_iso())
        ctx.store.add_evidence(evidence)
        ids.append(evidence.id)
    return ids


def add_asset(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    kind = kwargs.get("kind")
    value = str(kwargs.get("value") or "").strip()
    if not value:
        return ToolResult.failure("value is required")
    asset_meta = kwargs.get("meta") if isinstance(kwargs.get("meta"), Mapping) else {
        "agent": ctx.agent, "task_id": ctx.task_id}
    try:
        asset = _upsert_asset(ctx, str(kind) if kind else None, value,
                              parent_value=kwargs.get("parent_value"), meta=asset_meta)
    except ToolError as exc:
        return ToolResult.failure(exc.message, data={"allowed_kinds": list(ASSET_KINDS)})
    audit(ctx, "add_asset", "upserted", asset.id, {"kind": asset.kind, "value": asset.value})
    data = _asset_brief(asset)
    return ToolResult.success(data, text=json_dumps(data))


def anchor_node(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    node_id = str(kwargs.get("node_id") or "").strip()
    if not node_id:
        return ToolResult.failure("node_id is required")
    node = ctx.store.find_node(node_id)
    if node is None or node.project_id != ctx.project.id:
        return ToolResult.failure(f"node not found: {node_id}")
    value = str(kwargs.get("asset_value") or "").strip()
    if not value:
        return ToolResult.failure("asset_value is required")
    kind = kwargs.get("kind")
    try:
        asset = _find_asset_by_value(ctx, value)
        if asset is None:
            asset = _upsert_asset(ctx, str(kind) if kind else None, value)
        elif kind and str(kind).lower() != asset.kind:
            try:
                asset = ctx.store.upsert_asset(ctx.project.id, _enum(kind, ASSET_KINDS, "asset kind"),
                                               value)
            except ToolError as exc:
                return ToolResult.failure(exc.message)
    except ToolError as exc:
        return ToolResult.failure(exc.message)
    ctx.store.anchor(node.id, asset.id, note=str(kwargs.get("note") or ""))
    audit(ctx, "anchor_node", "linked", node.id, {"asset_id": asset.id, "value": asset.value})
    data = {"node_id": node.id, "asset_id": asset.id, "value": asset.value, "kind": asset.kind}
    return ToolResult.success(data, text=json_dumps(data))


def graph_query(ctx: ToolContext, kwargs: dict[str, Any]) -> ToolResult:
    view = str(kwargs.get("view") or "overview").strip().lower()
    if view not in {"overview", "facts", "findings", "assets", "intents", "todos", "traces"}:
        return ToolResult.failure("view must be overview|facts|findings|assets|intents|todos|traces")
    query = str(kwargs.get("query") or "").strip().lower()
    limit = clamp_int(kwargs.get("limit"), 1, 200, 50)
    store = ctx.store
    project_id = ctx.project.id

    def matches(text: str) -> bool:
        return not query or query in (text or "").lower()

    if view == "overview":
        node_counts = store.counts(project_id)
        open_intents = [n for n in store.list_nodes(project_id, kind="intent", limit=200)
                        if n.status in {"open", "active"}]
        findings = [n for n in store.list_nodes(project_id, kind="finding", limit=200)]
        findings.sort(key=lambda n: (SEVERITY_RANK.get(n.severity, 99), -n.seq))
        data = {"view": "overview", "counts": node_counts,
                "goal": {"id": ctx.project.id, "name": ctx.project.name, "goal": ctx.project.goal},
                "open_intents": [_node_brief(n) for n in open_intents[:limit]],
                "top_findings": [_node_brief(n) for n in findings[:limit]],
                "todos": [{"id": t.id, "title": t.title, "status": t.status} for t in
                          store.list_todos(project_id)[:limit]]}
        return ToolResult.success(data, text=json_dumps(data))

    if view == "todos":
        todos = [t for t in store.list_todos(project_id)]
        items = [{"id": t.id, "position": t.position, "title": t.title, "status": t.status,
                  "detail": truncate(t.detail, 300), "depends_on": t.depends_on}
                 for t in todos if matches(t.title + " " + t.detail)][:limit]
        data = {"view": "todos", "count": len(items), "items": items}
        return ToolResult.success(data, text=json_dumps(data))

    if view == "traces":
        traces = store.list_traces(project_id, limit=limit, newest_first=True)
        items = [{"id": t.id, "task_id": t.task_id, "agent": t.agent, "kind": t.kind,
                  "tool": t.tool_name, "content": truncate(t.content, 300),
                  "created_at": t.created_at} for t in traces if matches(t.content + " " + t.tool_name)]
        data = {"view": "traces", "count": len(items), "items": items[:limit]}
        return ToolResult.success(data, text=json_dumps(data))

    if view == "assets":
        assets = store.list_assets(project_id, limit=4000)
        items = [_asset_brief(a) for a in assets if matches(a.value)][:limit]
        by_kind: dict[str, int] = {}
        for asset in assets:
            by_kind[asset.kind] = by_kind.get(asset.kind, 0) + 1
        data = {"view": "assets", "count": len(items), "total": len(assets),
                "by_kind": by_kind, "items": items}
        return ToolResult.success(data, text=json_dumps(data))

    kind = {"facts": "fact", "findings": "finding", "intents": "intent"}.get(view, view)
    nodes = store.list_nodes(project_id, kind=kind, limit=2000)
    selected = [n for n in nodes if matches(n.title + " " + n.body)]
    if view == "findings":
        selected.sort(key=lambda n: (SEVERITY_RANK.get(n.severity, 99), -n.seq))
    items = [_node_brief(n) for n in selected[:limit]]
    data = {"view": view, "count": len(items), "total": len(nodes), "items": items}
    return ToolResult.success(data, text=json_dumps(data))


